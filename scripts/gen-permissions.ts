import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
	ACTIONS,
	BASTION_ROLES,
	BREAK_GLASS_ROLE,
	ORG_ROLES,
	ORG_ROLE_ACTIONS,
	SESSION_ONLY_ACTIONS,
	SITE_ROLES,
	SITE_ROLE_ACTIONS,
	STEP_UP_ACTIONS,
	STEP_UP_WINDOW_MS,
	SUPPORT_ROLES,
	actionDef,
	type Action
} from '../src/shared/permissions';

const here = dirname(fileURLToPath(import.meta.url));
export const OUTPUT = resolve(here, '../docs/reference/permissions.md');

function table(header: string[], rows: string[][]): string {
	const widths = header.map((h, i) => Math.max(h.length, 3, ...rows.map((r) => r[i]!.length)));
	const line = (cells: string[]) =>
		`| ${cells.map((c, i) => c.padEnd(widths[i]!)).join(' | ')} |`;
	return [
		line(header),
		`| ${widths.map((w) => '-'.repeat(w)).join(' | ')} |`,
		...rows.map(line)
	].join('\n');
}

function notes(action: Action): string {
	const def = actionDef(action);
	const out: string[] = [];
	if (def.sessionOnly) out.push('session only');
	if (def.stepUp) out.push('step-up');
	if (def.content) out.push('site content');
	if (def.entitlement) out.push(`plan feature ${def.entitlement}`);
	if (def.budget) out.push(`budget ${def.budget}`);
	return out.join(', ');
}

const list = (items: readonly string[]) => items.map((i) => `- \`${i}\``).join('\n');

export function render(): string {
	const dashboardActions = ACTIONS.filter((a) => {
		const scope = actionDef(a).scope;
		return scope !== 'admin' && scope !== 'account';
	});
	const matrix = table(
		[
			'Action',
			'Scope',
			...ORG_ROLES.map((r) => `Org ${r}`),
			...SITE_ROLES.map((r) => `Site ${r}`),
			'Notes'
		],
		dashboardActions.map((a) => [
			`\`${a}\``,
			actionDef(a).scope,
			...ORG_ROLES.map((r) => (ORG_ROLE_ACTIONS[r].includes(a) ? 'x' : '')),
			...SITE_ROLES.map((r) => (SITE_ROLE_ACTIONS[r].includes(a) ? 'x' : '')),
			notes(a)
		])
	);
	const accountAndAdmin = table(
		['Action', 'Who', 'Notes'],
		ACTIONS.filter((a) => ['admin', 'account'].includes(actionDef(a).scope)).map((a) => {
			const def = actionDef(a);
			const who =
				def.scope === 'account' ? 'any signed-in user' : `platform admin, ${def.platform}`;
			return [`\`${a}\``, who, notes(a)];
		})
	);
	const bastion = table(
		['Dashboard role', 'Bastion role'],
		[
			...Object.entries(BASTION_ROLES).map(([site, bastionRole]) => [
				`site ${site}`,
				bastionRole
			]),
			['platform admin', 'never `operator` on a customer box']
		]
	);
	const minutes = STEP_UP_WINDOW_MS / 60000;

	return `# Permissions

This file is generated by \`bun scripts/gen-permissions.ts\` from \`src/shared/permissions.ts\`. Edit that file and regenerate. A unit test fails when this file is stale.

One function, \`authorize\`, decides every request. It denies anything it does not recognise.

## How a request is decided

The checks run in this order, and the first failure ends the request:

1. Platform flags: a suspended user, or a suspended organisation outside billing and audit.
2. Membership of the organisation.
3. Grants, from the organisation down to a department, then a site. Grants add up and never narrow one another.
4. Delegation from another organisation, limited to site actions.
5. API key scopes, intersected with what the key's issuer holds today.
6. Policy groups, which cap every layer above, then the action's own step-up rule.
7. Plan entitlement.
8. Change budget.

An action marked step-up needs a passkey or a fresh code within ${minutes} minutes. An API key cannot present a step-up, so it never performs those actions.

## Roles and actions

Organisation roles are ${ORG_ROLES.map((r) => `\`${r}\``).join(', ')}. Site roles are ${SITE_ROLES.map((r) => `\`${r}\``).join(', ')}. An \`x\` means the role holds the action. The scope says how low the action is addressed: a grant at a level gives only actions at that level or below.

${matrix}

## Account and platform actions

Platform admin actions need the admin flag, the Cloudflare Access fact and the named platform permission. They never accept an API key. An admin acts inside an organisation only through a time-boxed support grant (roles ${SUPPORT_ROLES.map((r) => `\`${r}\``).join(' or ')}) or break-glass (role \`${BREAK_GLASS_ROLE}\`, a typed reason and a fresh step-up). Neither reaches actions marked site content.

${accountAndAdmin}

## Session-only actions

These refuse API keys. Every \`admin.*\` action refuses them too.

${list(SESSION_ONLY_ACTIONS)}

## Step-up actions

${list(STEP_UP_ACTIONS)}

## Delegation

An agency organisation receives \`maintainer\` or \`viewer\` on selected sites, or all sites, of a client organisation. The client's owner or admin creates it, the agency's owner or admin accepts it, and either side can revoke it. The effective permission is the minimum of the delegation role and the acting member's own role in the agency. Every action writes an audit row in both organisations.

## API keys

A key's scopes are a subset of its issuer's permissions when it is issued, and they are intersected with the issuer's permissions on every use. Session-only and step-up actions cannot be scoped into a key.

## Mapping to bastion roles

${bastion}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	mkdirSync(dirname(OUTPUT), { recursive: true });
	writeFileSync(OUTPUT, render());
}
