import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOGUE_ROWS, type CatalogueRow } from '../src/shared/health/catalogue';

const here = dirname(fileURLToPath(import.meta.url));
export const OUTPUT = resolve(here, '../docs/reference/health-catalogue.md');

function table(header: string[], rows: string[][]): string {
	const widths = header.map((h, i) => Math.max(h.length, 3, ...rows.map((r) => r[i]!.length)));
	const line = (cells: string[]) =>
		`| ${cells.map((c, i) => c.padEnd(widths[i]!)).join(' | ')} |`;
	return [
		line(header),
		`| ${widths.map((w) => '-'.repeat(w)).join(' | ')} |`,
		...rows.map(line)
	].join('\n');
}

const cell = (s: string) => s.replace(/\|/g, '\\|');

function undo(row: CatalogueRow): string {
	return 'handle' in row.undo ? `\`${row.undo.handle}\`` : `none: ${row.undo.none}`;
}

function preconditions(row: CatalogueRow): string {
	return row.preconditions.length === 0 ? 'none' : row.preconditions.join('; ');
}

export function render(): string {
	const rows = CATALOGUE_ROWS.map((r) => [
		`\`${r.repairId}\``,
		r.severity,
		r.handle === 'none' ? 'none' : `\`${r.handle}\``,
		r.class,
		r.automation,
		preconditions(r),
		String(r.attemptBound),
		String(r.cooldownMs),
		`\`${r.successPredicate}\``,
		undo(r),
		r.escalation,
		r.unverified ? 'yes' : 'no'
	]).map((cells) => cells.map(cell));

	const catalogue = table(
		[
			'Code',
			'Severity',
			'Handle',
			'Class',
			'Automation',
			'Preconditions',
			'Attempts',
			'Cool-down (ms)',
			'Success check',
			'Undo',
			'Escalation',
			'Unverified'
		],
		rows
	);

	return `---
title: Health catalogue
description: Every health check, what it measures and the repair attached to it, generated from the catalogue.
audience: [developer, department-owner]
type: generated
draft: true
---

# Health catalogue

This file is generated by \`bun scripts/gen-catalogue.ts\` from \`src/shared/health/catalogue.ts\`. Edit that file and regenerate. A unit test fails when this file is stale.

Each row is one failure code that the health tree or the repair ladder can act on. The handle is the route or operation that repairs it. \`none\` means no repair runs. The class decides whether a tool may run the repair unattended: \`safe\` changes nothing a visitor sees, \`rebuild\` discards derived state that comes back on its own, and \`stateful\` changes what the site serves.

A repair runs only when its preconditions hold. A failure that has not reached three same-code strikes stays on the lower rungs. Attempts and cool-downs come from the worker, and no row sets its own value yet.

The success check names the re-observation that shows the failure has cleared. The undo column names the route that reverses the repair, or gives the reason there is none.

Rows marked unverified describe a failure that the worker source does not contain. Their handles are planned behaviour and have not been run.

${catalogue}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	mkdirSync(dirname(OUTPUT), { recursive: true });
	writeFileSync(OUTPUT, render());
}
