import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EFFORT, EFFORT_STATES, type EffortRow } from '../src/shared/effort';

const here = dirname(fileURLToPath(import.meta.url));
export const OUTPUT = resolve(here, '../docs/reference/operator-effort.md');

function table(header: string[], rows: string[][]): string {
	const widths = header.map((h, i) => Math.max(h.length, 3, ...rows.map((r) => r[i]!.length)));
	const line = (cells: string[]) =>
		`| ${cells.map((c, i) => c.padEnd(widths[i]!)).join(' | ')} |`;
	return [
		line(header),
		`| ${widths.map((w) => '-'.repeat(w)).join(' | ')} |`,
		...rows.map(line)
	].join('\n');
}

const code = (text: string) => (text === 'none' ? 'none' : `\`${text}\``);

export function render(rows: readonly EffortRow[] = EFFORT): string {
	const totals = table(
		['State', 'Tasks'],
		[
			...EFFORT_STATES.map((state) => [
				state,
				String(rows.filter((r) => r.state === state).length)
			]),
			['total', String(rows.length)]
		]
	);
	const body = table(
		[
			'Task',
			'State',
			'Screens',
			'Dashboard operation',
			'Worker route',
			'Must know today',
			'Remains once there is a button',
			'Area'
		],
		rows.map((r) => [
			r.task,
			r.state,
			String(r.screens),
			code(r.dashboardOperation),
			code(r.workerRoute),
			r.mustKnowToday.join('; '),
			r.leftAfter,
			r.scheduled
		])
	);

	return `---
title: Operator effort
description: The recurring maintainer tasks, what a Drupal maintainer must know to do each one today, and what stays with them once the dashboard has a button for it.
audience: [developer, department-owner]
type: generated
draft: true
---

# Operator effort

This file is generated by \`bun scripts/gen-effort.ts\` from \`src/shared/effort.ts\`. Edit that file and regenerate. A unit test fails when this file is stale.

Each row is one task a maintainer does on a site. The state says how far the dashboard goes today. \`one-button\` means one action in the dashboard completes the task. \`partial\` means a screen or a route exists, but the task still takes more than one step, or the dashboard has no control for it. \`blocked\` means the Worker has no route for the task yet.

The counts are screens and steps named in the source screens and docs. They are not timed.

## Totals

${totals}

## Tasks

${body}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	mkdirSync(dirname(OUTPUT), { recursive: true });
	writeFileSync(OUTPUT, render());
}
