const pages = Object.entries(TREE).flatMap(([dir, names]) =>
	names.map((name) => (dir ? `${dir}/${name}` : name))
);

const NOT_DRAFT = new Set(['index', 'changelog']);

const fileOf = (page: string) => join(docsDir, `${page}.md`);

const frontmatterOf = (text: string) => {
	const match = text.match(/^---\n([\s\S]*?)\n---\n/);
	if (!match) throw new Error('missing frontmatter');
	return parse(match[1]!);
};

describe('docs map', () => {
	it('lists each page once', () => {
		expect(new Set(pages).size).toBe(pages.length);
	});

	it.each(pages)('%s exists', async (page) => {
		await expect(stat(fileOf(page))).resolves.toBeDefined();
	});

	it.each(pages)('%s has valid frontmatter', async (page) => {
		const data = frontmatterOf(await readFile(fileOf(page), 'utf8'));
		expect(frontmatter.safeParse(data).success).toBe(true);
		expect(frontmatter.parse(data).draft).toBe(!NOT_DRAFT.has(page));
	});

	it('links in index.md resolve to files', async () => {
		const text = await readFile(fileOf('index'), 'utf8');
		const links = [...text.matchAll(/\]\((\/docs\/[^)\s#]+)\)/g)].map((m) => m[1]!);
		expect(links.length).toBeGreaterThan(0);
		for (const link of links) {
			const page = link.slice('/docs/'.length);
			await expect(stat(fileOf(page))).resolves.toBeDefined();
		}
	});
});
